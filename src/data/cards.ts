export function cardFor(topic: { 구간: string | null; 근거축: string | null; 키: string }): Card | null {
  const 구간 = topic.구간 || "";
  if (구간.includes("제품페이지조회→데모신청") && (topic.근거축 === null || topic.근거축 === "세그먼트")) {
    return CARDS["제품페이지조회→데모신청:Primary"];
  }
  if (구간.includes("데모신청→계약체결")) {
    return CARDS["데모신청→계약체결:Secondary"];
  }
  if (topic.키.startsWith("threshold:low_usage_renewal_rate")) {
    return CARDS["저활용계정갱신개입"];
  }
  return null;
}
